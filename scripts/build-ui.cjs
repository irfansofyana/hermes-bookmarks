'use strict';
const fs=require('node:fs'),path=require('node:path'),esbuild=require('esbuild');
const root=path.resolve(__dirname,'..');
const markdown=esbuild.buildSync({stdin:{contents:'export {lexer} from "marked";',resolveDir:root},bundle:true,format:'iife',globalName:'HBMarkdown',target:'es2022',minify:true,write:false,legalComments:'inline'}).outputFiles[0].text;
const shared=['chat-transport.js','chat-session.js','chat-markdown.js','library-state.js','library-dialog.js','library-form.js','library-detail.js','library-navigation.js','library-items.js','library-import.js','library-bulk.js','library.js','chat-panel.js'].map(file=>fs.readFileSync(path.join(root,'ui',file),'utf8')).join('\n');
const styles=['chat.css','library-workspace.css','library-bulk.css'].map(file=>fs.readFileSync(path.join(root,'ui',file),'utf8')).join('\n');
const header='/* Generated by scripts/build-ui.cjs. Edit ui/ sources, not this file. */\n'+'/*! Bundled Marked license\n'+fs.readFileSync(path.join(root,'node_modules/marked/LICENSE'),'utf8').replaceAll('*/','* /')+'\n*/\n';
const core=markdown+'\n'+shared+'\nconst styles='+JSON.stringify(styles)+';\n';
const outputs={
 'desktop/plugin.js':header+`import { host, useValue, ROUTES_AREA, SIDEBAR_NAV_AREA, Button, Input, Dialog, DialogContent, DialogTitle, DialogDescription } from '@hermes/plugin-sdk';
import * as React from 'react';
${core}
const currentScope=()=>JSON.stringify([host.state.connectionId?.get()||'local',host.state.profile?.get()||'default']);
const Workspace=createBookmarksWorkspace(React,{request:(ctx,route,init)=>ctx.rest(route,init),currentScope,
 createTransport:(identity,scope)=>createDesktopChatTransport(host,{profile:identity.profile,connection:JSON.parse(scope)[0]})},{Button,Input,Dialog:typeof Dialog==='undefined'?undefined:Dialog,DialogContent:typeof DialogContent==='undefined'?undefined:DialogContent,DialogTitle:typeof DialogTitle==='undefined'?undefined:DialogTitle,DialogDescription:typeof DialogDescription==='undefined'?undefined:DialogDescription},styles);
function Page({ctx}){
 const profile=host.state.profile?useValue(host.state.profile):'default';
 const connection=host.state.connectionId?useValue(host.state.connectionId):'local';
 const scope=JSON.stringify([connection,profile]);
 return React.createElement(Workspace,{key:scope,ctx,scope});
}
export default {id:'hermes-bookmarks',name:'Bookmarks',defaultEnabled:false,register(ctx){
 ctx.register({id:'page',area:ROUTES_AREA,data:{path:'/bookmarks'},render:()=>React.createElement(Page,{ctx})});
 ctx.register({id:'nav',area:SIDEBAR_NAV_AREA,data:{path:'/bookmarks',label:'Bookmarks',codicon:'bookmark'}});
}};\n`,
 'dashboard/dist/index.js':header+`(function(){
'use strict';
const SDK=window.__HERMES_PLUGIN_SDK__;
if(!SDK?.React||!SDK.fetchJSON)throw Error('Hermes Dashboard SDK is unavailable');
${core}
const Workspace=createBookmarksWorkspace(SDK.React,{createTransport:()=>createDashboardChatTransport(SDK),
 request:(_ctx,route,init)=>SDK.fetchJSON('/api/plugins/hermes-bookmarks'+route,init?{method:init.method,headers:{'Content-Type':'application/json'},body:JSON.stringify(init.body)}:undefined)},SDK.components||{},styles);
window.__HERMES_PLUGINS__.register('hermes-bookmarks',Workspace);
})();\n`
};
let stale=false;
for(const [file,value] of Object.entries(outputs)){
 const target=path.join(root,file);
 if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==value){console.error('Stale: '+file);stale=true;}}
 else{fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,value);console.log('Built '+file);}
}
if(stale)process.exitCode=1;
