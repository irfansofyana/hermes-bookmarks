'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const shared = fs.readFileSync(path.join(root, 'ui/native-chat.js'), 'utf8') + '\n' + fs.readFileSync(path.join(root, 'ui/library.js'), 'utf8');
const styles = fs.readFileSync(path.join(root, 'ui/library.css'), 'utf8');
const header = '/* Generated by scripts/build-ui.cjs. Edit ui/library.js and ui/library.css. */\n';
const core = `${shared}\nconst styles = ${JSON.stringify(styles)};\n`;
const outputs = {
  'desktop/plugin.js': header + `import { host, ROUTES_AREA, SIDEBAR_NAV_AREA, Button, Input } from '@hermes/plugin-sdk';
import * as React from 'react';
${core}
const Library = createLibrary(React, {request: (ctx, route, init) => ctx.rest(route, init), chat: createNativeChat(host)}, {Button, Input}, styles);
export default {id: 'hermes-bookmarks', name: 'Bookmarks', defaultEnabled: false,
  register(ctx) {
    ctx.register({id: 'page', area: ROUTES_AREA, data: {path: '/bookmarks'}, render: () => React.createElement(Library, {ctx})});
    ctx.register({id: 'nav', area: SIDEBAR_NAV_AREA, data: {path: '/bookmarks', label: 'Bookmarks', codicon: 'bookmark'}});
  }
};\n`,
  'dashboard/dist/index.js': header + `(function () {
'use strict';
const SDK = window.__HERMES_PLUGIN_SDK__;
if (!SDK?.React || !SDK.fetchJSON) throw Error('Hermes Dashboard SDK is unavailable');
${core}
const Library = createLibrary(SDK.React, {chat: createNativeChat(null), request: (_ctx, route, init) => SDK.fetchJSON('/api/plugins/hermes-bookmarks' + route,
 init ? {method: init.method, headers: {'Content-Type': 'application/json'}, body: JSON.stringify(init.body)} : undefined)}, SDK.components || {}, styles);
window.__HERMES_PLUGINS__.register('hermes-bookmarks', Library);
})();\n`,
};
let stale = false;
for (const [file, value] of Object.entries(outputs)) {
  const target = path.join(root, file);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== value) {console.error('Stale: ' + file); stale = true;}
  } else {fs.mkdirSync(path.dirname(target), {recursive: true}); fs.writeFileSync(target, value); console.log('Built ' + file);}
}
if (stale) process.exitCode = 1;
